// gardeForMillesime — calcule la fenêtre de garde d'un vin pour un millésime donné.
// Cherche dans MILLESIMES_DB (année + région + type) le "gardeMax" (colonne 5),
// sinon retombe sur wine.drinkUntil. Retourne { from, until } en années civiles.
export function gardeForMillesime(wine, year) {
  const y = Number(year)
  if (!wine || !y) return null
  const typeLabel = TYPE_LABELS[wine.type]
  const match = MILLESIMES_DB.find(row => {
    const [rowYear, rowType, rowRegion, rowAppellation] = row
    if (rowYear !== y) return false
    if (rowRegion !== wine.region) return false
    if (rowType && typeLabel && rowType !== typeLabel) return false
    // Match par appellation si possible, sinon on accepte juste année+région+type
    if (rowAppellation && wine.appellation && rowAppellation !== wine.appellation) {
      return false
    }
    return true
  }) || MILLESIMES_DB.find(row => {
    const [rowYear, rowType, rowRegion] = row
    return rowYear === y && rowRegion === wine.region && (!rowType || !typeLabel || rowType === typeLabel)
  })
  const gardeMax = match ? match[5] : wine.drinkUntil
  return {
    from: y + wine.drinkFrom,
    until: y + gardeMax,
  }
}

