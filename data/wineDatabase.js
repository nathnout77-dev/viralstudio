// difficulte : 'facile' (à aimer direct) | 'explorer' (un cran plus loin) | 'pointu' (pour curieux avertis)
// jauges : puissance (léger→puissant), douceur (sec→doux), tanins (souple→costaud) — 1 à 5
function vin(o) {
  return {
    typeLabel: TYPE_LABELS[o.type],
    color: o.color || TYPE_COLORS[o.type],
    carafage: null,
    domaines: [],
    ...o,
  }
}

